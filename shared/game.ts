export function travelDome(world:World,id:string):boolean {
  const player=world.players.find(p=>p.id===id),e=world.entities.find(entity=>entity.id===player?.entityId);
  if(!player||!e)return false;
  let pose:{x:number;z:number;yaw:number}|null;
  if(e.inDome){
    if(e.domeReturn==='island')pose=sideSpawn(world,e.kind,'island',e);
    else {try{pose=spawnPosition(world,e.kind);}catch{return false;}}
  }else pose=domeSpawn(world,e.kind);
  if(!pose)return false;
  const inDome=!e.inDome;
  if(inDome)e.domeReturn=isRocketIsland(e.x,e.z)||(e.supportId==='ferry'&&(world.ferry.phase==='to-island'||world.ferry.phase==='island'))?'island':'sf';
  leaveParking(world.parking,id);leaveRace(world.races,id);removeFerryPassenger(world.ferry,e.id);
  placeEntity(e,pose,inDome,world.time);resetAchievementFlight(player);return true;
}
