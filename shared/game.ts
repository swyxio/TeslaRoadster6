export function interact(world:World,playerId:string):void {
  const player=world.players.find(p=>p.id===playerId),e=world.entities.find(e=>e.id===player?.entityId);
  if(!player||!e||e.supportId===null||Math.abs(e.speed)>5||ferrySecured(world.ferry,e))return;
  if(e.kind==='person'){
    const car=world.entities.filter(other=>other.kind!=='person'&&!other.driver&&!other.police&&requiredLevelAt(other.x,other.z)<=player.delivery.level&&other.inDome===e.inDome&&(other.supportId===e.supportId||(e.inDome&&e.supportId==='ground'&&other.supportId==='dome'&&other.y<.05))&&Math.hypot(other.x-e.x,other.z-e.z)<Math.max(7,dimensions(other.kind).length/2+2)).sort((a,b)=>Math.hypot(a.x-e.x,a.z-e.z)-Math.hypot(b.x-e.x,b.z-e.z))[0];
    if(!car)return;
    leaveParking(world.parking,playerId);
    leaveRace(world.races,playerId);
    if(world.ferry.arrivals.includes(e.id))world.ferry.arrivals=[...new Set(world.ferry.arrivals.filter(id=>id!==e.id).concat(car.id))];
    car.driver=playerId;car.autopilot=false;car.speed=0;car.pushX=0;car.pushZ=0;car.lastJump=e.lastJump;car.lastFlip=e.lastFlip;car.domeReturn=e.domeReturn;player.entityId=car.id;world.entities=world.entities.filter(other=>other!==e);resetAchievementFlight(player);
  }else{
    const width=dimensions(e.kind).width/2+1.3,length=dimensions(e.kind).length/2+1.3;
    const exits=[{angle:Math.PI/2,distance:width},{angle:-Math.PI/2,distance:width},{angle:Math.PI,distance:length},{angle:0,distance:length}];
    const person=exits.map(({angle,distance})=>{
      const p=makeEntity(`person-${playerId}`,'person',e.x-Math.sin(e.yaw+angle)*distance,e.z-Math.cos(e.yaw+angle)*distance,playerId);
      const floorExit=e.inDome&&e.supportId==='dome'&&e.y<.05;
      const y=e.supportId==='ferry'?(ferryDocked(world.ferry)&&onFerryDeck(world.ferry,p.x,p.z)?0:null):floorExit?terrainHeight(p.x,p.z):supportHeight(e.supportId!,p.x,p.z);
      if(y===null)return null;p.y=y;p.inDome=e.inDome;p.domeReturn=e.domeReturn;p.supportId=floorExit?'ground':e.supportId;return p;
    }).find((p):p is Entity=>p!==null&&requiredLevelAt(p.x,p.z)<=player.delivery.level&&fits(world,p));
    if(!person)return;
    leaveParking(world.parking,playerId);
    leaveRace(world.races,playerId);
    if(world.ferry.arrivals.includes(e.id))world.ferry.arrivals.push(person.id);
    person.lastJump=e.lastJump;person.lastFlip=e.lastFlip;release(e,world);player.entityId=person.id;world.entities.push(person);cleanupCars(world);resetAchievementFlight(player);
  }
}
export function chooseVehicle(world:World,id:string,kind:VehicleId):boolean {
  const player=world.players.find(p=>p.id===id),old=world.entities.find(e=>e.id===player?.entityId);
  if(!player||!old||old.supportId===null||old.supportId==='ferry'||old.loopAngle!==null||Math.abs(old.speed)>1||!Object.hasOwn(VEHICLES,kind)||VEHICLES[kind].brand!=='Tesla')return false;
  const spawn=old.inDome?domeSpawn(world,kind,old):isRocketIsland(old.x,old.z)?sideSpawn(world,kind,'island',old):spawnPosition(world,kind);
  if(!spawn)return false;
  leaveParking(world.parking,id);leaveRace(world.races,id);
  release(old,world);
  world.entities=world.entities.filter(e=>e.id!==`person-${id}`&&!(e.owner===id&&!e.driver));
  const car=makeEntity(`ride-${id}-${world.time.toFixed(2)}`,kind,spawn.x,spawn.z,id);car.owner=id;placeEntity(car,spawn,old.inDome,world.time);car.domeReturn=old.domeReturn;car.lastJump=old.lastJump;car.lastFlip=old.lastFlip;
  world.entities.push(car);player.entityId=car.id;resetAchievementFlight(player);return true;
}
export function buyUpgrade(world:World,id:string,upgrade:UpgradeId):boolean {
  const player=world.players.find(p=>p.id===id),car=world.entities.find(e=>e.id===player?.entityId);
  if(!player||!car||car.kind==='person'||car.driver!==id||!Object.hasOwn(UPGRADES,upgrade))return false;
  updateOta(player,world.time);
  if(!shopFor(car)&&!player.delivery.ota.active)return false;
  const price=upgrade==='tank'?tankUpgradePrice(car.tankLevel):UPGRADES[upgrade].price;
  if(player.delivery.cash<price)return false;
  if(upgrade==='rocket'&&hasRockets(car))return false;
  if((upgrade==='economy'||upgrade==='tank')&&!hasRockets(car))return false;
  if(upgrade==='service'){
    if(car.health>=100&&car.air>=100)return false;
    car.health=100;car.air=100;
  }else if(upgrade==='tank'){
    if(car.tankLevel>=MAX_TANK_LEVEL)return false;
    car.tankLevel=(car.tankLevel+1) as TankLevel;car.air=100;
  }else{
    if(car.upgrades[upgrade])return false;
    car.upgrades[upgrade]=true;
    if(upgrade==='rocket')car.air=100;
  }
  player.delivery.cash-=price;
  return true;
}
