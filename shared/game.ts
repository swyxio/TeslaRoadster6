export function interact(world:World,playerId:string):void {
  const player=world.players.find(p=>p.id===playerId),e=world.entities.find(e=>e.id===player?.entityId);
  if(!player||!e||e.supportId===null||Math.abs(e.speed)>5)return;
  if(e.kind==='person'){
    const car=world.entities.filter(other=>other.kind!=='person'&&!other.driver&&!other.police&&other.inDome===e.inDome&&(other.supportId===e.supportId||(e.inDome&&e.supportId==='ground'&&other.supportId==='dome'&&other.y<.05))&&Math.hypot(other.x-e.x,other.z-e.z)<Math.max(7,dimensions(other.kind).length/2+2)).sort((a,b)=>Math.hypot(a.x-e.x,a.z-e.z)-Math.hypot(b.x-e.x,b.z-e.z))[0];
    if(!car)return;
    car.driver=playerId;car.autopilot=false;car.speed=0;car.pushX=0;car.pushZ=0;car.lastJump=e.lastJump;car.lastFlip=e.lastFlip;player.entityId=car.id;world.entities=world.entities.filter(other=>other!==e);resetAchievementFlight(player);
  }else{
    const width=dimensions(e.kind).width/2+1.3,length=dimensions(e.kind).length/2+1.3;
    const exits=[{angle:Math.PI/2,distance:width},{angle:-Math.PI/2,distance:width},{angle:Math.PI,distance:length},{angle:0,distance:length}];
    const person=exits.map(({angle,distance})=>{
      const p=makeEntity(`person-${playerId}`,'person',e.x-Math.sin(e.yaw+angle)*distance,e.z-Math.cos(e.yaw+angle)*distance,playerId);
      const floorExit=e.inDome&&e.supportId==='dome'&&e.y<.05;
      const y=floorExit?terrainHeight(p.x,p.z):supportHeight(e.supportId!,p.x,p.z);if(y===null)return null;p.y=y;p.inDome=e.inDome;p.supportId=floorExit?'ground':e.supportId;return p;
    }).find((p):p is Entity=>p!==null&&fits(world,p));
    if(!person)return;
    person.lastJump=e.lastJump;person.lastFlip=e.lastFlip;release(e,world);player.entityId=person.id;world.entities.push(person);cleanupCars(world);resetAchievementFlight(player);
  }
}
