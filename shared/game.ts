function applyImpulse(e:Entity,x:number,z:number){const fx=-Math.sin(e.yaw),fz=-Math.cos(e.yaw),forward=x*fx+z*fz;e.speed+=forward;e.pushX+=x-forward*fx;e.pushZ+=z-forward*fz;e.vx+=x;e.vz+=z;}
type Vector3={x:number;y:number;z:number};
const dot3=(a:Vector3,b:Vector3)=>a.x*b.x+a.y*b.y+a.z*b.z;
function domeTangent(e:Entity,v:Vector3):Vector3 {
  const arc=surfaceArc(e);if(arc===null)return v;
  const s=domeSurface(arc),normal={x:0,y:s.normalY,z:s.normalZ},n=dot3(v,normal);
  return {x:v.x,y:v.y-n*normal.y,z:v.z-n*normal.z};
}
function moveDomeBody(e:Entity,v:Vector3):void {
  const old={x:e.x,y:e.y,z:e.z,supportId:e.supportId};
  const arc=surfaceArc(e);
  e.x+=v.x;
  if(e.supportId==='dome'&&arc!==null){
    const s=domeSurface(arc);e.domeS=((arc+v.y*s.tangentY+v.z*s.tangentZ)%DOME_PERIMETER+DOME_PERIMETER)%DOME_PERIMETER;
    const next=domeSurface(e.domeS);e.y=next.y;e.z=next.z;
  }else{
    e.y+=v.y;e.z+=v.z;
    if(e.supportId!==null)followSupport(e,old);
  }
  constrainDome(e,e.kind!=='person'&&!!VEHICLES[e.kind].airThrusters);
}
function addDomeVelocity(e:Entity,v:Vector3):void {
  if(e.supportId==='dome'&&e.domeS!==null){
    const s=domeSurface(e.domeS),along=v.y*s.tangentY+v.z*s.tangentZ;
    e.speed+=-Math.sin(e.yaw)*v.x-Math.cos(e.yaw)*along;
    e.vx=-Math.sin(e.yaw)*e.speed;e.vy=-Math.cos(e.yaw)*e.speed*s.tangentY;e.vz=-Math.cos(e.yaw)*e.speed*s.tangentZ;
  }else if(e.supportId!==null)applyImpulse(e,v.x,v.z);
  else{
    e.vx+=v.x;e.vy+=v.y;e.vz+=v.z;
    e.speed=-Math.sin(e.yaw)*e.vx-Math.cos(e.yaw)*e.vz;
    e.pushX=e.vx+Math.sin(e.yaw)*e.speed;e.pushZ=e.vz+Math.cos(e.yaw)*e.speed;
  }
}
function resolveDomeContact(a:Entity,b:Entity):boolean {
  const hit=domeContact(a,b);if(!hit)return false;
  const ma=dimensions(a.kind).massKg,mb=dimensions(b.kind).massKg;
  const normalFor=(e:Entity):Vector3=>{
    if(hit.space==='world')return {x:hit.nx,y:hit.ny,z:hit.nz};
    const s=domeSurface(surfaceArc(e)!);return {x:hit.nx,y:hit.ns*s.tangentY,z:hit.ns*s.tangentZ};
  };
  const na=normalFor(a),nb=normalFor(b),ta=domeTangent(a,na),tb=domeTangent(b,nb);
  const denominator=dot3(na,ta)/ma+dot3(nb,tb)/mb;if(denominator<1e-10)return false;
  const oldA={x:a.x,y:a.y,z:a.z,supportId:a.supportId,domeS:a.domeS},oldB={x:b.x,y:b.y,z:b.z,supportId:b.supportId,domeS:b.domeS};
  const shift=(hit.depth+.01)/denominator;
  moveDomeBody(a,{x:-ta.x*shift/ma,y:-ta.y*shift/ma,z:-ta.z*shift/ma});
  moveDomeBody(b,{x:tb.x*shift/mb,y:tb.y*shift/mb,z:tb.z*shift/mb});
  if(solid(a))Object.assign(a,oldA);if(solid(b))Object.assign(b,oldB);
  const closing=dot3({x:b.vx,y:b.vy,z:b.vz},nb)-dot3({x:a.vx,y:a.vy,z:a.vz},na);
  if(closing<0){
    const impulse=-1.25*closing/denominator;
    addDomeVelocity(a,{x:-ta.x*impulse/ma,y:-ta.y*impulse/ma,z:-ta.z*impulse/ma});
    addDomeVelocity(b,{x:tb.x*impulse/mb,y:tb.y*impulse/mb,z:tb.z*impulse/mb});
    const damage=Math.max(0,-closing-5)*.35,total=ma+mb;a.health=Math.max(5,a.health-damage*mb/total);b.health=Math.max(5,b.health-damage*ma/total);
  }
  return true;
}
type PreviousPose={x:number;y:number;z:number;supportId:SupportId|null};
// Follow only the surface already occupied, or a ramp connected at ground level.
// This also runs after vehicle separation, without advancing time a second time.
function followSupport(e:Entity,old:PreviousPose):void {
  if(e.supportId==='dome'&&e.domeS!==null){
    const previous=domeSurface(e.domeS);
    e.domeS=((e.domeS+(e.z-old.z)*previous.tangentZ+(e.y-old.y)*previous.tangentY)%DOME_PERIMETER+DOME_PERIMETER)%DOME_PERIMETER;
    const surface=domeSurface(e.domeS);e.y=surface.y;e.z=surface.z;return;
  }
  if(e.supportId==='stunt-loop'||e.supportId===null)return;
  if(e.supportId==='ground'){
    const deck=overpassHeight(e.x,e.z);
    const entersDeck=(old.x<OVERPASS.start&&e.x>=OVERPASS.start)||(old.x>OVERPASS.end&&e.x<=OVERPASS.end);
    const ramp=rampHeight(e.x,e.z);
    if(deck!==null&&entersDeck&&Math.abs(old.z-OVERPASS.z)<=OVERPASS.width/2){e.supportId='overpass';e.y=deck;}
    else if(ramp!==null&&old.x<=STUNT_RAMP.start&&e.x>=STUNT_RAMP.start&&Math.abs(old.z-STUNT_RAMP.z)<=STUNT_RAMP.width/2){e.supportId='stunt-ramp';e.y=ramp;}
    else {const ground=terrainHeight(e.x,e.z);if(ground!==null)e.y=ground;}
    e.vy=e.supportId==='stunt-ramp'?e.vx*STUNT_RAMP.height/(STUNT_RAMP.end-STUNT_RAMP.start):0;
    return;
  }
  const height=supportHeight(e.supportId,e.x,e.z);
  if(height!==null){e.y=height;e.vy=e.supportId==='stunt-ramp'?e.vx*STUNT_RAMP.height/(STUNT_RAMP.end-STUNT_RAMP.start):0;return;}
  const ground=terrainHeight(e.x,e.z);
  const rampEnd=e.supportId==='overpass'&&Math.abs(e.z-OVERPASS.z)<=OVERPASS.width/2&&
    ((old.x>=OVERPASS.start&&e.x<OVERPASS.start)||(old.x<=OVERPASS.end&&e.x>OVERPASS.end));
  const stuntStart=e.supportId==='stunt-ramp'&&old.x>=STUNT_RAMP.start&&e.x<STUNT_RAMP.start&&Math.abs(e.z-STUNT_RAMP.z)<=STUNT_RAMP.width/2;
  if((rampEnd||stuntStart)&&ground!==null&&Math.abs(old.y-ground)<.5){e.supportId='ground';e.y=ground;e.vy=0;}
  else if(e.supportId==='overpass'&&contact(body(e),deckBody)){e.y=deckTopAt(e.x);e.vy=0;}
  else if(e.supportId.startsWith('roof:')){
    const roof=BUILDINGS[Number(e.supportId.slice(5))];
    if(roof&&contact(body(e),{...roof,yaw:0})){e.y=roof.h;e.vy=0;}
    else {e.supportId=null;e.vy=0;}
  }else if(e.supportId==='stunt-ramp'){
    // The lip launches the car along the real ramp tangent.
    e.supportId=null;
    if(e.x>STUNT_RAMP.end){e.y=STUNT_RAMP.height+(e.x-STUNT_RAMP.end)*STUNT_RAMP.height/(STUNT_RAMP.end-STUNT_RAMP.start);e.vy=e.vx*STUNT_RAMP.height/(STUNT_RAMP.end-STUNT_RAMP.start);}
    else e.vy=0;
  }else {e.supportId=null;e.vy=0;}
}
function landAirborne(world:World,e:Entity,old:PreviousPose):void {
  if(e.supportId!==null)return;
  let landing:{id:SupportId;y:number}|null=null;
  const ground=terrainHeight(e.x,e.z),oldGround=terrainHeight(old.x,old.z);
  if(ground!==null&&e.y<=ground&&(oldGround===null||old.y>=oldGround-.001))landing={id:'ground',y:ground};
  const deck=overpassHeight(e.x,e.z),oldDeck=overpassHeight(old.x,old.z)??deckTopAt(old.x);
  if(deck!==null&&e.vy<=0&&old.y>=oldDeck-.001&&e.y<=deck&&(!landing||deck>landing.y))landing={id:'overpass',y:deck};
  const ramp=rampHeight(e.x,e.z),oldRamp=rampHeight(old.x,old.z)??ramp;
  if(ramp!==null&&oldRamp!==null&&e.vy<=0&&old.y>=oldRamp-.001&&e.y<=ramp&&(!landing||ramp>landing.y))landing={id:'stunt-ramp',y:ramp};
  for(const b of nearbyBuildings(e.x,e.z,Math.max(dimensions(e.kind).length,dimensions(e.kind).width))){
    if(e.vy<=0&&old.y>=b.h&&e.y<=b.h&&contact(body(e),{...b,yaw:0})&&(!landing||b.h>landing.y))landing={id:`roof:${BUILDINGS.indexOf(b)}`,y:b.h};
  }
  if(landing){
    const impact=-e.vy;if(impact>12)e.health=Math.max(5,e.health-(impact-12)*.5);
    e.supportId=landing.id;e.y=landing.y;e.vy=landing.id==='stunt-ramp'?e.vx*STUNT_RAMP.height/(STUNT_RAMP.end-STUNT_RAMP.start):0;
    e.pitch=0;e.roll=0;e.pitchRate=0;e.rollRate=0;e.flipRemaining=0;
  }else if(e.y<=0&&ground===null){
    const spawn=spawnPosition(world,e.kind);
    Object.assign(e,spawn,{y:terrainHeight(spawn.x,spawn.z)??0,supportId:'ground',vx:0,vy:0,vz:0,pitch:0,roll:0,flipRemaining:0,loopAngle:null,speed:0,pushX:0,pushZ:0,autopilot:false});
  }
  if(e.supportId!=='overpass'&&contact(body(e),deckBody)){
    const bottom=deckTopAt(e.x)-OVERPASS.thickness,height=dimensions(e.kind).height;
    const oldBottom=deckTopAt(old.x)-OVERPASS.thickness;
    const wasUnder=!!contact(body({...e,x:old.x,z:old.z}),deckBody)&&old.y+height<=oldBottom+.001;
    if(wasUnder&&e.y+height>bottom&&e.vy>0){e.y=bottom-height;e.vy=0;}
  }
}

/** Admit physical fly-ins only after their upright body fits inside the capsule. */
function enterDomeIfInside(e:Entity):void {
  if(e.inDome)return;
  if(Math.abs(e.x-DOME.x)>DOME.halfLength||Math.abs(e.z-DOME.z)>DOME.flatHalfWidth+DOME.radius||e.y<0||e.y>2*DOME.radius)return;
  const size=dimensions(e.kind),c=Math.abs(Math.cos(e.yaw)),s=Math.abs(Math.sin(e.yaw));
  const halfX=(c*size.width+s*size.length)/2,halfZ=(s*size.width+c*size.length)/2;
  if(Math.abs(e.x-DOME.x)+halfX>DOME.halfLength)return;
  const curved=Math.max(0,Math.abs(e.z-DOME.z)+halfZ-DOME.flatHalfWidth);
  if(curved>DOME.radius)return;
  const height=Math.sqrt(Math.max(0,DOME.radius**2-curved**2));
  if(e.y<DOME.radius-height||e.y+size.height>DOME.radius+height)return;
  e.inDome=true;e.autopilot=false;
}

/** Clamp to the closed capsule. Only the ball may use the goal apertures. */
function constrainDome(e:Entity,rocket:boolean):void {
  if(!e.inDome)return;
  const size=dimensions(e.kind),cos=Math.abs(Math.cos(e.yaw)),sin=Math.abs(Math.sin(e.yaw));
  const xLimit=DOME.halfLength+DOME.x-(cos*size.width+sin*size.length)/2;
  const xMin=2*DOME.x-xLimit;
  if(e.x<xMin||e.x>xLimit){
    const side=e.x<xMin?-1:1;e.x=clamp(e.x,xMin,xLimit);
    if(e.vx*side>0)e.vx=0;
    e.speed=0;e.pushX=0;
  }
  if(e.supportId==='dome')return;
  const w=DOME.flatHalfWidth,r=DOME.radius;
  if(e.supportId==='ground'){
    // Ordinary cars can drive on the flat floor but have no wall adhesion.
    const limit=w-(sin*size.width+cos*size.length)/2;
    if(Math.abs(e.z-DOME.z)>limit){e.z=DOME.z+Math.sign(e.z-DOME.z)*limit;e.speed=0;e.vz=0;e.pushZ=0;}
    return;
  }
  let s:number|null=null;
  const z=e.z-DOME.z;
  if(z>w){
    const a=Math.atan2(z-w,r-e.y),distance=Math.hypot(z-w,e.y-r);
    if(distance>r)s=2*w+r*clamp(a,0,Math.PI);
  }else if(z< -w){
    const a=Math.atan2(-z-w,e.y-r),distance=Math.hypot(-z-w,e.y-r);
    if(distance>r)s=4*w+Math.PI*r+r*clamp(a,0,Math.PI);
  }else if(e.y>2*r)s=2*w+Math.PI*r+(w-z);
  if(s===null)return;
  const surface=domeSurface(s),toward=e.vy*surface.normalY+e.vz*surface.normalZ;
  e.y=surface.y;e.z=surface.z;
  if(rocket&&toward<0){
    const across=e.vy*surface.tangentY+e.vz*surface.tangentZ;
    e.speed=Math.hypot(e.vx,across);e.yaw=Math.atan2(-e.vx,-across);
    e.vy=across*surface.tangentY;e.vz=across*surface.tangentZ;
    e.supportId='dome';e.domeS=s;e.loopAngle=null;e.pitch=0;e.roll=0;e.flipRemaining=0;
  }else if(toward<0){
    // Non-Rocket bodies bounce from the surface rather than adhering to it.
    e.vy-=1.2*toward*surface.normalY;e.vz-=1.2*toward*surface.normalZ;
  }
}

export function step(world:World,inputs:Map<string,Input>,dt:number):void {
  if(!Number.isFinite(dt)||dt<=0)return;
  dt=Math.min(dt,.05);
  // Keep fast vehicles from jumping over another vehicle in a 50 ms tick.
  // This caps travel near one meter per substep under normal speed limits.
  const maxSpeed=world.entities.reduce((max,e)=>Math.max(max,Math.abs(e.speed)+Math.hypot(e.pushX,e.pushZ),Math.hypot(e.vx,e.vz)),0);
  const steps=Math.min(8,Math.max(1,Math.ceil(maxSpeed*dt)));
  for(let i=0;i<steps;i++)advance(world,inputs,dt/steps);
}
