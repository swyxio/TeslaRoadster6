const deckBody={x:(OVERPASS.start+OVERPASS.end)/2,z:OVERPASS.z,w:OVERPASS.end-OVERPASS.start,d:OVERPASS.width,yaw:0};
function deckTopAt(x:number):number {
  return overpassHeight(clamp(x,OVERPASS.start,OVERPASS.end),OVERPASS.z)!;
}
function insideDeckVolume(e:Entity):boolean {
  if(e.supportId==='overpass'||!contact(body(e),deckBody))return false;
  const top=deckTopAt(e.x),bottom=top-OVERPASS.thickness;
  return e.y<top-.001&&e.y+dimensions(e.kind).height>bottom+.001;
}
function solid(e:Entity):boolean {
  const b=body(e),radius=Math.abs(Math.cos(e.yaw))*b.w/2+Math.abs(Math.sin(e.yaw))*b.d/2;
  const rz=Math.abs(Math.sin(e.yaw))*b.w/2+Math.abs(Math.cos(e.yaw))*b.d/2;
  const islandJump=e.supportId==='island-jump'?null:islandJumpHeight(e.x,e.z);
  return e.x-radius<MAP_BOUNDS.minX||e.x+radius>MAP_BOUNDS.maxX||e.z-rz<MAP_BOUNDS.minZ||e.z+rz>MAP_BOUNDS.maxZ||(e.supportId==='ground'&&!isSurface(e.x,e.z))||insideDeckVolume(e)||(islandJump!==null&&e.y<islandJump-.001)||nearbyBuildings(e.x,e.z,Math.max(radius,rz)+2).some(building=>e.y<building.h-.001&&!!contact(b,{...building,yaw:0}));
}
function fits(world:World,e:Entity,ignore?:Entity):boolean{return e.supportId!==null&&!solid(e)&&!world.entities.some(other=>other!==ignore&&other!==e&&e.y<other.y+dimensions(other.kind).height&&other.y<e.y+dimensions(e.kind).height&&!!contact(body(e),body(other)));}
function sideSpawn(world:World,kind:Entity['kind'],side:FerrySide,ignore?:Entity):{x:number;z:number;yaw:number}|null {
  const xs=side==='sf'?[-12,0,12]:[-36,-24,-12,0,12,24,36];
  const zs=side==='sf'?[-235,-220,-205,-190]:[-1120,-1135,-1150,-1165];
  for(const z of zs)for(const x of xs){
    const candidate=makeEntity('candidate',kind,x,z);
    const d=dimensions(kind);
    const wholeBody=[-1,1].every(a=>[-1,1].every(b=>terrainHeight(x+a*d.width/2,z+b*d.length/2)!==null));
    if(wholeBody&&fits(world,candidate,ignore))return {x,z,yaw:side==='sf'?Math.PI:0};
  }
  return null;
}
function moveToSide(world:World,e:Entity,side:FerrySide):boolean {
  const spawn=sideSpawn(world,e.kind,side,e);if(!spawn)return false;
  Object.assign(e,spawn,{y:terrainHeight(spawn.x,spawn.z)??0,supportId:'ground',vx:0,vy:0,vz:0,pitch:0,roll:0,pitchRate:0,yawRate:0,rollRate:0,flipRemaining:0,loopAngle:null,speed:0,pushX:0,pushZ:0,autopilot:false,steering:0,thrusters:0,jumpBurstUntil:0});
  if(e.npc&&!e.driver&&engageAutopilot(e))e.pauseUntil=world.time+2;
  return true;
}
function spawnPosition(world:World,kind:Entity['kind']='roadster'):{x:number;z:number;yaw:number} {
  // New drivers face the open city and their first delivery, not the locked bridge.
  const bayApproach={x:40,z:60,yaw:Math.PI/2};
  const bayCandidate=makeEntity('candidate',kind,bayApproach.x,bayApproach.z);bayCandidate.yaw=bayApproach.yaw;
  if(fits(world,bayCandidate))return bayApproach;
  for(let i=0;i<192;i++){
    const road=[60,0,-60,-120,-180,-240][Math.floor(i/32)];
    const x=road+(i%2?3.5:-3.5),z=120-Math.floor(i/2)%16*14;
    const candidate=makeEntity('candidate',kind,x,z);
    if(fits(world,candidate))return {x,z,yaw:0};
  }
  // Sparse outer apron is also checked: never spawn on an occupied point.
  for(let x=-220;x<=220;x+=20)for(let z of [210,-210])if(fits(world,makeEntity('candidate',kind,x,z)))return {x,z,yaw:0};
  throw new Error('No free spawn position');
}
// Safe, deterministic floor slots accommodate even the longest catalog tractor.
function domeSpawn(world:World,kind:Entity['kind'],ignore?:Entity):{x:number;z:number;yaw:number}|null {
  const size=dimensions(kind);
  const ball=world.soccer.ball;
  const slots:{x:number;z:number}[]=[{x:DOME.x-30,z:DOME.z}];
  for(let x=DOME.x-65;x<=DOME.x+65;x+=10)for(let z=DOME.z-17.5;z<=DOME.z+17.5;z+=5)slots.push({x,z});
  for(const {x,z} of slots){
    const candidate=makeEntity('candidate',kind,x,z);candidate.yaw=-Math.PI/2;candidate.inDome=true;
    if(ball&&ball.y-DOME.ballRadius<size.height&&Math.abs(x-ball.x)<size.length/2+DOME.ballRadius+1&&Math.abs(z-ball.z)<size.width/2+DOME.ballRadius+1)continue;
    if(fits(world,candidate,ignore))return {x,z,yaw:candidate.yaw};
  }
  return null;
}
